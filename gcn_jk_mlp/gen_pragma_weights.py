#!/usr/bin/env python3
"""
Regenerates pragma_weights.h from the SAME checkpoint the GCN backbone uses.

The teammate's pragma_weights.h (kept as pragma_weights_from_teammate.h.orig)
was built from a different training run, one not present on this machine. The
pragma MLPs and the GCN are trained together inside one HierarchicalMoE, so
their weights must come from the same checkpoint or the MLPs receive
embeddings they were never trained on.

Array names, sizes and order are identical to the teammate's header, so
pragma_mlp.cpp compiles against either one unchanged.

Mapping (checkpoint key -> array):
    experts.N.MLPs_per_pragma.<mlp>.layers.<L>.weight  ->  eN_<mlp>_l<L>_w   [out*in], row-major
    experts.N.MLPs_per_pragma.<mlp>.layers.<L>.bias    ->  eN_<mlp>_l<L>_b   [out]

Usage
    cd ~/gcn_jk_mlp
    source ~/fpga_accel/venv/bin/activate
    python gen_pragma_weights.py
"""
import glob
import os
import re

import numpy as np
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "pragma_weights.h")
TEAMMATE = os.path.join(HERE, "pragma_weights_from_teammate.h.orig")

HMOE_ROOT = "/home/rizwanpathan/hierarchical_moe/HierarchicalMoE"

EXPERTS = (0, 1, 2)
MLPS = ("tile", "pipeline", "parallel", "merge")   # pragma_as_MLP_list order + merge
PER_LINE = 6


def find_checkpoint():
    # same glob as dump_tb_data.py -- one checkpoint for GCN and pragma MLP
    hits = sorted(glob.glob(os.path.join(
        HMOE_ROOT, "src/logs/**/*gnn-gcn/run1/1000_val_model_state_dict.pth"),
        recursive=True))
    if not hits:
        raise FileNotFoundError("no GCN checkpoint under src/logs")
    return hits[0]


def arrays(sd):
    """(name, flat float32 array) in the teammate's order."""
    out = []
    for e in EXPERTS:
        for m in MLPS:
            for lyr in (0, 1):
                pre = f"experts.{e}.MLPs_per_pragma.{m}.layers.{lyr}"
                w = sd[f"{pre}.weight"].numpy().astype(np.float32)
                b = sd[f"{pre}.bias"].numpy().astype(np.float32)
                out.append((f"e{e}_{m}_l{lyr}_w", w.reshape(-1)))
                out.append((f"e{e}_{m}_l{lyr}_b", b.reshape(-1)))
    return out


def fmt(v):
    # %.9g round-trips every float32 exactly
    s = "%.9g" % float(v)
    if "." not in s and "e" not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def parse_header(path):
    """{name: (declared size, values)} from a header in this format."""
    src = open(path).read()
    res = {}
    for name, n, body in re.findall(
            r"static const float (\w+)\[(\d+)\] = \{(.*?)\};", src, re.S):
        vals = np.array([float(t.strip().rstrip("f")) for t in body.split(",") if t.strip()],
                        dtype=np.float32)
        res[name] = (int(n), vals)
    return res


def main():
    ck = find_checkpoint()
    sd = torch.load(ck, map_location="cpu")
    arrs = arrays(sd)
    rel = os.path.relpath(ck, HMOE_ROOT)

    with open(OUT, "w") as f:
        f.write("#pragma once\n\n")
        f.write(f"// Auto-generated by gen_pragma_weights.py from\n//   {rel}\n")
        f.write("// -- the same checkpoint the GCN backbone weights come from. Do not edit.\n\n")
        f.write("// Row-major PyTorch Linear weights: [out_features][in_features].\n\n")
        for name, a in arrs:
            f.write(f"static const float {name}[{a.size}] = {{\n")
            for i in range(0, a.size, PER_LINE):
                f.write("    " + ", ".join(fmt(v) for v in a[i:i + PER_LINE]) + ",\n")
            f.write("};\n\n")

    print(f"checkpoint : {rel}")
    print(f"wrote      : {OUT}  ({len(arrs)} arrays, {sum(a.size for _, a in arrs)} floats)")

    # ---- check 1: values read back bit-exact ----------------------------
    mine = parse_header(OUT)
    for name, a in arrs:
        n, v = mine[name]
        assert n == a.size and np.array_equal(v, a), f"{name}: round-trip mismatch"
    print("check      : every array reads back bit-exact from the checkpoint")

    # ---- check 2: same layout as the teammate's header -------------------
    if os.path.exists(TEAMMATE):
        theirs = parse_header(TEAMMATE)
        assert list(theirs) == list(mine), "array names/order differ from teammate's header"
        for name in mine:
            assert theirs[name][0] == mine[name][0], f"{name}: size differs from teammate's header"
        print(f"check      : names, order and sizes identical to {os.path.basename(TEAMMATE)}")


if __name__ == "__main__":
    main()
